// Builds public/data/coast.js: the coastline of the North, South and Stewart islands, simplified for the drawn map.
// Source: LINZ NZ Coastlines and Islands Polygons (Topo 1:50k), Environment Canterbury redistribution snapshot as
// saved by the Codex version (read-only). Licence: CC BY 4.0 — "Contains data sourced from the LINZ Data Service".
// Stewart Island comes from Natural Earth 1:10m (public domain) if it is not in the LINZ file.
//   node scripts/build-coast.mjs [tolerance=0.6]
import { readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const WORK = process.env.COAST_WORK || join(homedir(), 'Documents/Codex/2026-10-31/mac-jev-typesafe-api-key-typesafe/work');
const TOL = Number(process.argv[2]) || 0.6; // map units (the map is 920 units wide)
const project = ([lat, lon]) => [(lon - 166.2) * 72 + 10, (-34.2 - lat) * 100 + 10];

function rings(file) {
  const g = JSON.parse(readFileSync(join(WORK, file), 'utf8'));
  const out = [];
  for (const f of g.features || (g.type === "Feature" ? [g] : [{ geometry: g }])) {
    const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
    for (const p of polys) out.push(p[0].map(([lon, lat]) => [lat, lon]));
  }
  return out;
}
// Ramer–Douglas–Peucker in projected units, so the tolerance means the same thing everywhere on the map.
function rdp(pts, tol) {
  const P = pts.map(project);
  const keep = new Uint8Array(P.length);
  keep[0] = keep[P.length - 1] = 1;
  const stack = [[0, P.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop();
    const [ax, ay] = P[a], [bx, by] = P[b];
    const dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1e-9;
    let far = -1, best = tol;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * P[i][0] - dx * P[i][1] + bx * ay - by * ax) / len;
      if (d > best) { best = d; far = i; }
    }
    if (far > 0) { keep[far] = 1; stack.push([a, far], [far, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
const area = (r) => Math.abs(r.reduce((s, [la, lo], i) => { const [lb, lob] = r[(i + 1) % r.length]; return s + (lo * lb - lob * la); }, 0) / 2);
const centroidLat = (r) => r.reduce((s, p) => s + p[0], 0) / r.length;

const linz = rings('linz-main-islands-simplified.geojson').sort((a, b) => area(b) - area(a));
const north = linz.find((r) => centroidLat(r) > -41.7);
const south = linz.find((r) => centroidLat(r) < -41 && centroidLat(r) > -46.5);
let stewart = linz.find((r) => centroidLat(r) < -46.6);
let stewartSrc = 'LINZ';
if (!stewart) {
  stewart = rings('ne_10m_new_zealand.geojson').filter((r) => centroidLat(r) < -46.6 && centroidLat(r) > -47.4).sort((a, b) => area(b) - area(a))[0];
  stewartSrc = 'Natural Earth 1:10m';
}
// A closed ring: split at the point farthest from the start so neither half has identical endpoints.
function rdpRing(r, tol) {
  const ring = r[0][0] === r[r.length - 1][0] && r[0][1] === r[r.length - 1][1] ? r.slice(0, -1) : r;
  const [x0, y0] = project(ring[0]);
  let k = 1, best = 0;
  ring.forEach((p, i) => { const [x, y] = project(p); const d = Math.hypot(x - x0, y - y0); if (d > best) { best = d; k = i; } });
  return [...rdp(ring.slice(0, k + 1), tol), ...rdp([...ring.slice(k), ring[0]], tol).slice(1, -1)];
}
const fmt = (r) => `[${rdpRing(r, TOL).map(([a, b]) => `[${a.toFixed(3)},${b.toFixed(3)}]`).join(',')}]`;
const out = `// GENERATED by scripts/build-coast.mjs (tolerance ${TOL} map units). Do not edit by hand.
// North and South Island: LINZ NZ Coastlines and Islands Polygons (Topo 1:50k) — contains data sourced from the
// LINZ Data Service licensed for reuse under CC BY 4.0. Rakiura/Stewart Island: ${stewartSrc}.
// Generalised for an illustrated map; not for navigation.
export const COAST_CREDIT = 'Coastline: LINZ Data Service (CC BY 4.0)${stewartSrc === 'LINZ' ? '' : ' · Natural Earth'}';
export const NORTH = ${fmt(north)};
export const SOUTH = ${fmt(south)};
export const STEWART = ${fmt(stewart)};
`;
writeFileSync(new URL('../public/data/coast.js', import.meta.url), out);
console.log(`north ${rdpRing(north, TOL).length} pts, south ${rdpRing(south, TOL).length}, stewart ${rdpRing(stewart, TOL).length} (${stewartSrc}); ${(out.length / 1024).toFixed(0)} KB`);
