export function strings(lang) {
  const base = STR.en;
  const over = STR[lang] || {};
  return new Proxy({}, { get: (_, k) => (k in over ? over[k] : base[k]) });
}

// Pick a language's text from a data object { en, zh, ... }, falling back to English.
export const pick = (obj, lang) => (obj ? obj[lang] ?? obj.en : '');
