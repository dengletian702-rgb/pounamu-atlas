// Writes public/sw.js: an offline copy of the site's own files (pages, scripts, styles, data, fonts, 640 px photos).
// The worker is registered only when a visitor presses "Save for offline"; it never caches /api/ or other sites.
//   node scripts/build-sw.mjs
import { readdirSync, statSync, writeFileSync, readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const PUB = fileURLToPath(new URL('../public/', import.meta.url));
const walk = (d) => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));
const files = walk(PUB).map((f) => `/${relative(PUB, f)}`)
  .filter((f) => f !== '/sw.js' && !/\/\./.test(f) && !/-1280\.jpg$/.test(f) && /\.(html|js|css|woff2|svg|jpg|png|json|webmanifest)$/.test(f));
const hash = createHash('sha1');
for (const f of files) hash.update(readFileSync(join(PUB, f)));
const version = hash.digest('hex').slice(0, 10);
let bytes = 0;
for (const f of files) bytes += statSync(join(PUB, f)).size;

writeFileSync(join(PUB, 'sw.js'), `// GENERATED by scripts/build-sw.mjs — offline copy of this site's own files (version ${version}).
const CACHE = 'pounamu-${version}';
const FILES = ${JSON.stringify(['/', '/compare', '/trip', ...files])};
const PAGE = (p) => (/^\\/r\\/[a-z0-9-]+\\/?$/.test(p) ? '/route.html' : /^\\/(compare|trip)\\/?$/.test(p) ? p.replace(/\\/$/, '') : null);

self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('pounamu-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
// Network first (so a running local server always wins), the saved copy when offline.
self.addEventListener('fetch', (e) => {
  const u = new URL(e.request.url);
  if (e.request.method !== 'GET' || u.origin !== location.origin || u.pathname.startsWith('/api/')) return;
  e.respondWith(fetch(e.request).then((res) => {
    if (res.ok && FILES.includes(u.pathname)) { const copy = res.clone(); caches.open(CACHE).then((c) => c.put(u.pathname, copy)); }
    return res;
  }).catch(async () => (await caches.match(u.pathname)) || (await caches.match(PAGE(u.pathname) || '/')) || Response.error()));
});
`);
console.log(`sw.js: ${files.length} files, ${(bytes / 1024).toFixed(0)} KB, version ${version}`);
